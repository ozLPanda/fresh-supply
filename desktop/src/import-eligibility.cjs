const fs = require("node:fs/promises");

const FORMAT = "ovoshi-help-pristine-reference";
const EXCLUDED_TABLES = new Set([
  "flyway_schema_history",
  "auth_sessions",
  "web_push_subscriptions",
  "external_api_credentials",
  "external_api_credential_permissions",
  "external_api_request_logs",
]);
const SEEDED_TABLES = new Set([
  "permissions",
  "roles",
  "users",
  "user_roles",
  "role_permissions",
  "user_permissions",
  "wallets",
  "warehouses",
  "project_settings",
]);

function excludedTable(name) {
  return (
    EXCLUDED_TABLES.has(name) || name.startsWith("external_api_request_logs_")
  );
}

function quoteIdentifier(value) {
  return '"' + String(value).replaceAll('"', '""') + '"';
}

/** SQL values are read as PostgreSQL text, preserving bigint and numeric precision.
 * Only nondeterministic bootstrap fields are masked. Other user/profile/permission
 * values remain part of the comparison, including null and soft-delete state. */
function normalizeTable(table) {
  const columns = table.columns.map((column) => ({
    name: column.name,
    type: column.type,
    notNull: Boolean(column.notNull),
  }));
  const rows = table.rows.map((row) =>
    columns.map((column, index) => {
      if (
        table.name === "users" &&
        ["phone", "password_hash"].includes(column.name)
      )
        return "<bootstrap>";
      if (
        SEEDED_TABLES.has(table.name) &&
        ["created_at", "updated_at"].includes(column.name) &&
        /^timestamp/.test(column.type)
      )
        return "<generated>";
      const value = Array.isArray(row) ? row[index] : row[column.name];
      if (value === undefined)
        throw new Error("Missing database cell in pristine snapshot.");
      return value === null ? null : String(value);
    }),
  );
  rows.sort((left, right) =>
    JSON.stringify(left).localeCompare(JSON.stringify(right), "en"),
  );
  return { name: table.name, columns, rows };
}

function normalizeReference(reference) {
  if (
    reference?.format !== FORMAT ||
    reference.schemaVersion !== 1 ||
    !Array.isArray(reference.tables)
  ) {
    throw new Error("Unsupported pristine reference.");
  }
  const names = new Set();
  const tables = reference.tables.map((table) => {
    if (
      !table ||
      typeof table.name !== "string" ||
      names.has(table.name) ||
      excludedTable(table.name) ||
      !Array.isArray(table.columns) ||
      !Array.isArray(table.rows)
    ) {
      throw new Error("Invalid pristine reference table.");
    }
    names.add(table.name);
    if (
      table.columns.some(
        (column) =>
          typeof column.name !== "string" || typeof column.type !== "string",
      )
    ) {
      throw new Error("Invalid pristine reference column.");
    }
    return normalizeTable(table);
  });
  tables.sort((left, right) => left.name.localeCompare(right.name, "en"));
  return {
    format: FORMAT,
    schemaVersion: 1,
    appVersion: reference.appVersion,
    tables,
  };
}

async function readDatabaseReference(client, { appVersion } = {}) {
  const { rows: names } = await client.query(`
    SELECT c.relname AS name FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND c.relkind IN ('r','p') AND NOT c.relispartition
    ORDER BY c.relname`);
  const tables = [];
  for (const { name } of names) {
    if (excludedTable(name)) continue;
    const { rows: columns } = await client.query(
      `
      SELECT a.attname AS name, pg_catalog.format_type(a.atttypid,a.atttypmod) AS type,
             a.attnotnull AS "notNull"
      FROM pg_catalog.pg_attribute a
      JOIN pg_catalog.pg_class c ON c.oid=a.attrelid
      JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
      WHERE n.nspname='public' AND c.relname=$1 AND a.attnum>0 AND NOT a.attisdropped
      ORDER BY a.attnum`,
      [name],
    );
    if (!columns.length)
      throw new Error("Cannot inspect local database columns.");
    const projection = columns
      .map(
        ({ name: column }) =>
          `${quoteIdentifier(column)}::text AS ${quoteIdentifier(column)}`,
      )
      .join(",");
    const { rows } = await client.query(
      `SELECT ${projection} FROM public.${quoteIdentifier(name)}`,
    );
    tables.push({ name, columns, rows });
  }
  return normalizeReference({
    format: FORMAT,
    schemaVersion: 1,
    appVersion,
    tables,
  });
}

/** Build-time assertion: the blueprint itself must never describe business data.
 * Full seed content is generated by current Flyway, not copied from any installation. */
function assertPristineBlueprint(reference) {
  const normalized = normalizeReference(reference);
  const byName = new Map(normalized.tables.map((table) => [table.name, table]));
  for (const table of normalized.tables) {
    if (!SEEDED_TABLES.has(table.name) && table.rows.length)
      throw new Error("Business data in pristine reference.");
  }
  const objects = (name) => {
    const table = byName.get(name);
    if (!table) throw new Error("Missing seed table in pristine reference.");
    return table.rows.map((row) =>
      Object.fromEntries(
        table.columns.map((column, index) => [column.name, row[index]]),
      ),
    );
  };
  const users = objects("users");
  const wallets = objects("wallets");
  const warehouses = objects("warehouses");
  const settings = objects("project_settings");
  if (
    users.length !== 1 ||
    users[0].email !== "admin@active.kz" ||
    users[0].name !== "Администратор" ||
    users[0].active !== "true" ||
    users[0].deleted_at !== null ||
    wallets.length !== 1 ||
    wallets[0].user_id !== users[0].id ||
    Number(wallets[0].balance) !== 0 ||
    warehouses.length !== 1 ||
    warehouses[0].code !== "MAIN" ||
    warehouses[0].name_ru !== "Основной склад" ||
    warehouses[0].active !== "true" ||
    settings.length !== 2 ||
    !settings.some(
      (row) => row.key === "search.ai.enabled" && row.value === "true",
    ) ||
    !settings.some(
      (row) =>
        row.key === "commerce.wholesale.minQuantity" && row.value === "10",
    ) ||
    objects("user_roles").length !== 1 ||
    objects("user_permissions").length !== 0
  ) {
    throw new Error("Unexpected seed values in pristine reference.");
  }
  const roles = objects("roles")
    .map((row) => row.code)
    .sort();
  const expectedRoles = [
    "administrator",
    "seller",
    "senior_seller",
    "accountant",
    "moderator",
    "china_sourcing",
    "dima",
    "installer",
  ].sort();
  if (JSON.stringify(roles) !== JSON.stringify(expectedRoles))
    throw new Error("Unexpected seed roles in pristine reference.");
  return normalized;
}

async function verifyPristineReference(client, referencePath, filesDir) {
  let expected;
  try {
    expected = assertPristineBlueprint(
      JSON.parse(await fs.readFile(referencePath, "utf8")),
    );
  } catch {
    return {
      eligible: false,
      reason:
        "В сборке нет подходящего эталона пустой базы. Импорт заблокирован.",
    };
  }
  try {
    if (typeof filesDir !== "string" || !filesDir) {
      return {
        eligible: false,
        reason: "Не указан каталог локальных файлов. Импорт заблокирован.",
      };
    }
    for (const table of [
      "external_api_credentials",
      "external_api_credential_permissions",
    ]) {
      const { rows } = await client.query(
        `SELECT EXISTS(SELECT 1 FROM public.${quoteIdentifier(table)} LIMIT 1) AS present`,
      );
      if (rows[0]?.present !== false) {
        return {
          eligible: false,
          reason:
            "В локальной базе уже настроен доступ к API. Импорт заблокирован.",
        };
      }
    }
    {
      const stat = await fs.lstat(filesDir).catch((error) => {
        if (error.code === "ENOENT") return null;
        throw error;
      });
      if (
        stat &&
        (!stat.isDirectory() ||
          stat.isSymbolicLink() ||
          (await fs.readdir(filesDir)).length)
      ) {
        return {
          eligible: false,
          reason:
            "В локальном файловом хранилище уже есть данные. Импорт заблокирован.",
        };
      }
    }
    const actual = await readDatabaseReference(client);
    if (JSON.stringify(actual.tables) !== JSON.stringify(expected.tables)) {
      return {
        eligible: false,
        reason:
          "Локальная база отличается от исходной пустой установки. Импорт заблокирован.",
      };
    }
    return { eligible: true };
  } catch {
    return {
      eligible: false,
      reason:
        "Не удалось проверить исходную пустую установку. Импорт заблокирован.",
    };
  }
}

module.exports = {
  verifyPristineReference,
  readDatabaseReference,
  normalizeReference,
  assertPristineBlueprint,
  excludedTable,
};
